using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Numos.API.Generators.Common;

/// <summary>
///     Builds generated source with four-space indentation and <c>\n</c> line endings on every platform.
/// </summary>
internal sealed class CodeWriter
{
    public static readonly string GeneratedCodeAttribute =
        "[global::System.CodeDom.Compiler.GeneratedCode(\"Numos.API.Generators\", \"" +
        typeof(CodeWriter).Assembly.GetName().Version +
        "\")]";

    private readonly StringBuilder _builder = new();
    private int _indent;

    public void Line(string text = "")
    {
        if (text.Length > 0)
            _builder.Append(' ', _indent * 4).Append(text);

        _builder.Append('\n');
    }

    public void Open()
    {
        Line("{");
        _indent++;
    }

    public void Close(string suffix = "")
    {
        _indent--;
        Line("}" + suffix);
    }

    /// <summary>
    ///     Writes the <c>auto-generated</c> marker and enables nullable annotations for the file.
    /// </summary>
    public void Header()
    {
        Line("// <auto-generated/>");
        Line("#nullable enable");
        Line();
    }

    public void OpenNamespace(PartialTypeModel type)
    {
        if (type.Namespace.Length == 0)
            return;

        Line("namespace " + type.Namespace);
        Open();
    }

    public void CloseNamespace(PartialTypeModel type)
    {
        if (type.Namespace.Length > 0)
            Close();
    }

    /// <summary>
    ///     Reopens every type in <paramref name="type" />'s chain as a partial declaration.
    /// </summary>
    /// <param name="type">The type to reopen.</param>
    /// <param name="baseList">Appended to the innermost declaration, such as <c> : IFoo</c>.</param>
    public void OpenTypeChain(PartialTypeModel type, string baseList = "")
    {
        EquatableArray<ContainingTypeModel> chain = type.ContainingTypes;
        for (int i = 0; i < chain.Count; i++)
        {
            string declaration = "partial " + chain[i].Keyword + " " + chain[i].Declaration;
            Line(i == chain.Count - 1 ? declaration + baseList : declaration);
            Open();
        }
    }

    public void CloseTypeChain(PartialTypeModel type)
    {
        for (int i = 0; i < type.ContainingTypes.Count; i++)
            Close();
    }

    public override string ToString()
    {
        return _builder.ToString();
    }

    /// <summary>
    ///     Prefixes <paramref name="identifier" /> with <c>@</c> when it is a reserved keyword.
    /// </summary>
    public static string Escape(string identifier)
    {
        return SyntaxFacts.GetKeywordKind(identifier) == SyntaxKind.None ? identifier : "@" + identifier;
    }
}