namespace Numos.API.Generators.Tests;

[TestFixture]
public sealed class AtmosSolverGeneratorTests
{
    private const string FireSource = """
                                      using Numos.API;

                                      namespace MyMod.Fire;

                                      [AtmosSolver("my-mod/fire", After = AtmosBuiltInSolvers.Thermodynamics, RunsPerSecond = 20,
                                          Neighbors = AtmosSolverNeighbors.All)]
                                      public sealed partial class FireSolver : IAtmosWorldSolver
                                      {
                                          public void Solve(AtmosWorldSolverContext context)
                                          {
                                          }
                                      }
                                      """;

    internal static GeneratorRunResult RunSolvers(
        out Compilation output,
        out ImmutableArray<Diagnostic> diagnostics, params string[] sources)
    {
        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions();
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(parseOptions, sources);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(parseOptions, generator: new AtmosSolverGenerator());
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out output, out diagnostics);
        return driver.GetRunResult().Results.Single();
    }

    [Test]
    public void PlainClass_GetsDescriptorAndModuleInitializer()
    {
        GeneratorRunResult result = RunSolvers(out Compilation output, out var diagnostics, FireSource);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(RoslynTestSupport.Errors(output), Is.Empty);
        Assert.That(output.GetDiagnostics().Where(static d => d.Severity == DiagnosticSeverity.Warning), Is.Empty);

        string source = GeneratorHarness.GeneratedSource(result, "MyMod.Fire.FireSolver.AtmosSolver.g.cs");
        string initializer = GeneratorHarness.GeneratedSource(result, AtmosSolverEmitter.ModuleInitializerHintName);
        Assert.Multiple(() =>
        {
            Assert.That(source, Does.StartWith("// <auto-generated/>\n#nullable enable\n"));
            Assert.That(
                source,
                Does.Contain(
                    "partial class FireSolver : global::Numos.API.IAtmosSolverDefinition<global::MyMod.Fire.FireSolver>"));

            Assert.That(source, Does.Contain("public static global::Numos.API.AtmosSolverDescriptor Descriptor =>"));
            Assert.That(source, Does.Contain("\"my-mod/fire\","));
            Assert.That(source, Does.Contain("typeof(global::MyMod.Fire.FireSolver),"));
            Assert.That(source, Does.Contain("static () => new global::MyMod.Fire.FireSolver(),"));
            Assert.That(source, Does.Contain("after: \"thermodynamics\","));
            Assert.That(source, Does.Contain("runsPerSecond: 20,"));
            Assert.That(
                source,
                Does.Contain(
                    "neighbors: new global::Numos.API.AtmosNeighborSelection(\"my-mod/fire#all\", true, static _ => true)));"));

            Assert.That(source, Does.Not.Contain("before:").And.Not.Contain("interval:"));
            Assert.That(
                initializer,
                Does.Contain("global::Numos.API.AtmosSolverCatalog.Register(global::MyMod.Fire.FireSolver.Descriptor);"));
        });
    }

    [TestCase("Cartesian", "my-mod/fire#cartesian", "true, static _ => false")]
    [TestCase("ExplicitLinks", "my-mod/fire#explicitlinks", "false, static _ => true")]
    public void NeighborModes_MapToSelections(string mode, string key, string arguments)
    {
        string source = FireSource.Replace("AtmosSolverNeighbors.All", "AtmosSolverNeighbors." + mode);
        GeneratorRunResult result = RunSolvers(out Compilation output, out var diagnostics, source);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(RoslynTestSupport.Errors(output), Is.Empty);
        Assert.That(
            GeneratorHarness.GeneratedSource(result, "MyMod.Fire.FireSolver.AtmosSolver.g.cs"),
            Does.Contain("new global::Numos.API.AtmosNeighborSelection(\"" + key + "\", " + arguments + ")"));
    }

    [Test]
    public void NoNeighbors_PassesNoSelection()
    {
        string source = FireSource.ReplaceLineEndings("\n").Replace(",\n    Neighbors = AtmosSolverNeighbors.All", "");
        GeneratorRunResult result = RunSolvers(out Compilation output, out var diagnostics, source);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(RoslynTestSupport.Errors(output), Is.Empty);
        Assert.That(
            GeneratorHarness.GeneratedSource(result, "MyMod.Fire.FireSolver.AtmosSolver.g.cs"),
            Does.Not.Contain("neighbors:"));
    }

    [Test]
    public void Selector_IsPassedAsMethodGroupWithItsKey()
    {
        const string source = """
                              using Numos.API;

                              namespace MyMod;

                              [AtmosSolver("my-mod/portal-sound", Before = AtmosBuiltInSolvers.GasReactions, Interval = 4)]
                              internal sealed partial class PortalSoundSolver : IAtmosWorldSolver
                              {
                                  [SolverNeighborSelector("my-mod/portal-sound#gas", IncludeCartesian = true)]
                                  private static bool SelectLink(AtmosExplicitLinkInfo link) =>
                                      (link.Flags & ExplicitLinkFlags.GasTransport) != 0;

                                  public void Solve(AtmosWorldSolverContext context)
                                  {
                                  }
                              }
                              """;

        GeneratorRunResult result = RunSolvers(out Compilation output, out var diagnostics, source);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(RoslynTestSupport.Errors(output), Is.Empty);
        string generated = GeneratorHarness.GeneratedSource(result, "MyMod.PortalSoundSolver.AtmosSolver.g.cs");
        Assert.Multiple(() =>
        {
            Assert.That(generated, Does.Contain("before: \"gas-reactions\","));
            Assert.That(generated, Does.Contain("interval: 4,"));
            Assert.That(
                generated,
                Does.Contain(
                    "new global::Numos.API.AtmosNeighborSelection(\"my-mod/portal-sound#gas\", true, " +
                    "global::MyMod.PortalSoundSolver.SelectLink)"));
        });
    }

    [Test]
    public void NestedClass_Compiles()
    {
        const string source = """
                              using Numos.API;

                              namespace MyMod;

                              public static partial class Outer
                              {
                                  internal partial class Middle
                                  {
                                      [AtmosSolver("my-mod/nested", RunsPerSecond = 10)]
                                      internal sealed partial class Inner : IAtmosWorldSolver
                                      {
                                          public void Solve(AtmosWorldSolverContext context)
                                          {
                                          }
                                      }
                                  }
                              }
                              """;

        GeneratorRunResult result = RunSolvers(out Compilation output, out var diagnostics, source);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(RoslynTestSupport.Errors(output), Is.Empty);
        Assert.That(output.GetDiagnostics().Where(static d => d.Severity == DiagnosticSeverity.Warning), Is.Empty);

        string generated = GeneratorHarness.GeneratedSource(result, "MyMod.Outer+Middle+Inner.AtmosSolver.g.cs");
        Assert.Multiple(() =>
        {
            Assert.That(generated, Does.Contain("partial class Outer\n"));
            Assert.That(generated, Does.Contain("partial class Middle\n"));
            Assert.That(
                generated,
                Does.Contain(
                    "partial class Inner : global::Numos.API.IAtmosSolverDefinition<global::MyMod.Outer.Middle.Inner>"));

            Assert.That(
                GeneratorHarness.GeneratedSource(result, AtmosSolverEmitter.ModuleInitializerHintName),
                Does.Contain("Register(global::MyMod.Outer.Middle.Inner.Descriptor);"));
        });
    }

    [Test]
    public void DerivedSolver_HidesTheBaseDescriptor()
    {
        const string source = """
                              using Numos.API;

                              namespace MyMod;

                              [AtmosSolver("my-mod/base", RunsPerSecond = 10)]
                              public partial class BaseSolver : IAtmosWorldSolver
                              {
                                  public void Solve(AtmosWorldSolverContext context)
                                  {
                                  }
                              }

                              [AtmosSolver("my-mod/derived", RunsPerSecond = 10)]
                              public sealed partial class DerivedSolver : BaseSolver
                              {
                              }
                              """;

        GeneratorRunResult result = RunSolvers(out Compilation output, out var diagnostics, source);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(RoslynTestSupport.Errors(output), Is.Empty);
        Assert.That(output.GetDiagnostics().Where(static d => d.Severity == DiagnosticSeverity.Warning), Is.Empty);
        Assert.Multiple(() =>
        {
            Assert.That(
                GeneratorHarness.GeneratedSource(result, "MyMod.BaseSolver.AtmosSolver.g.cs"),
                Does.Contain("public static global::Numos.API.AtmosSolverDescriptor Descriptor"));

            Assert.That(
                GeneratorHarness.GeneratedSource(result, "MyMod.DerivedSolver.AtmosSolver.g.cs"),
                Does.Contain("public static new global::Numos.API.AtmosSolverDescriptor Descriptor"));
        });
    }

    [Test]
    public void SerializeDependencyAndSolver_OnOneClass_Compile()
    {
        const string source = """
                              using Numos.API;
                              using Numos.CoreSim.State;

                              namespace MyMod;

                              /// <summary>
                              ///     Documented service.
                              /// </summary>
                              public interface IFireEvents
                              {
                              }

                              /// <summary>
                              ///     Documented solver.
                              /// </summary>
                              [AtmosSolver("my-mod/fire", RunsPerSecond = 20)]
                              public sealed partial class FireSolver : IAtmosWorldSolver
                              {
                                  [NumosSerialize] private int _ticks;

                                  [SolverDependency]
                                  private partial IFireEvents Events { get; }

                                  /// <inheritdoc />
                                  public void Solve(AtmosWorldSolverContext context)
                                  {
                                      _ = Events;
                                      _ticks++;
                                  }
                              }
                              """;

        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions().WithDocumentationMode(DocumentationMode.Diagnose);
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(parseOptions, source);
        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            [
                new StateGenerator().AsSourceGenerator(),
                new SolverDependencyGenerator().AsSourceGenerator(),
                new AtmosSolverGenerator().AsSourceGenerator(),
                new NumosModuleGenerator().AsSourceGenerator(),
            ],
            parseOptions: parseOptions);

        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation output, out var diagnostics);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(RoslynTestSupport.Errors(output), Is.Empty);
        Assert.That(output.GetDiagnostics().Where(static d => d.Severity == DiagnosticSeverity.Warning), Is.Empty);

        string[] hintNames = driver.GetRunResult().Results
            .SelectMany(static run => run.GeneratedSources)
            .Select(static generated => generated.HintName)
            .ToArray();

        Assert.That(
            hintNames,
            Is.SupersetOf(
                new[]
                {
                    "MyMod.FireSolver.NumosState.g.cs",
                    "MyMod.FireSolver.SolverDependencies.g.cs",
                    "MyMod.FireSolver.AtmosSolver.g.cs",
                    NumosModuleGenerator.HintName,
                }));
    }

    [Test]
    public void UnrelatedEdit_LeavesModelStepsCached()
    {
        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions();
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(parseOptions, FireSource);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(
            parseOptions,
            trackSteps: true,
            generator: new AtmosSolverGenerator());

        driver = driver.RunGenerators(compilation);

        CSharpCompilation edited = compilation.AddSyntaxTrees(
            CSharpSyntaxTree.ParseText(
                "namespace Other; internal static class Unrelated { }",
                parseOptions,
                path: "Unrelated.cs"));

        driver = driver.RunGenerators(edited);

        GeneratorRunResult result = driver.GetRunResult().Results.Single();
        IncrementalStepRunReason[] classes = result.TrackedSteps[AtmosSolverGenerator.ClassesStepName]
            .SelectMany(static run => run.Outputs)
            .Select(static output => output.Reason)
            .ToArray();

        Assert.That(classes, Is.Not.Empty);
        Assert.That(
            classes,
            Is.All.Matches<IncrementalStepRunReason>(static reason =>
                reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged));

        Assert.That(
            GeneratorHarness.SourceOutputReasons(result),
            Is.All.EqualTo(IncrementalStepRunReason.Cached));
    }

    [Test]
    public void ShiftedDeclaration_LeavesGeneratedFilesCached()
    {
        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions();
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(parseOptions, FireSource);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(
            parseOptions,
            trackSteps: true,
            generator: new AtmosSolverGenerator());

        driver = driver.RunGenerators(compilation);

        SyntaxTree tree = compilation.SyntaxTrees.Single();
        CSharpCompilation edited = compilation.ReplaceSyntaxTree(
            tree,
            CSharpSyntaxTree.ParseText("// moved\n\n" + FireSource, parseOptions, path: tree.FilePath));

        driver = driver.RunGenerators(edited);

        GeneratorRunResult result = driver.GetRunResult().Results.Single();
        Assert.That(
            result.TrackedSteps[AtmosSolverGenerator.ClassesStepName]
                .SelectMany(static run => run.Outputs)
                .Select(static output => output.Reason),
            Has.Some.EqualTo(IncrementalStepRunReason.Modified));

        foreach (string step in new[] { AtmosSolverGenerator.TypesStepName, AtmosSolverGenerator.ModuleInitializerStepName })
        {
            Assert.That(
                result.TrackedSteps[step]
                    .SelectMany(static run => run.Outputs)
                    .Select(static output => output.Reason),
                Is.Not.Empty.And.All.Matches<IncrementalStepRunReason>(static reason =>
                    reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged),
                step);
        }

        Assert.That(
            GeneratorHarness.SourceOutputReasons(result),
            Is.All.EqualTo(IncrementalStepRunReason.Cached));
    }
}
