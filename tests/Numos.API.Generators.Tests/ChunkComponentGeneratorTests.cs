        GeneratorRunResult[] results = GeneratorHarness.RunComponents(out _, out diagnostics, sources: [FireSource, conflicting]);
        Assert.That(GeneratorHarness.Ids(diagnostics), Is.EqualTo(new[] { "NUMOSCHUNK011", "NUMOSCHUNK011" }));
        Assert.That(results[0].GeneratedSources.Select(static source => source.HintName), Has.None.EqualTo("MyMod.Fire.ChunkComponent.g.cs"));
