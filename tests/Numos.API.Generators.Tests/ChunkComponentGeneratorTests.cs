    [Test]
    public void AllFieldsScratch_HasChecksTheFirstFieldAndTurnsFalseAfterARestore()
    {
        // With no saved field, the first scratch field stands in. A restore drops its storage, so the component reads
        // as absent until something creates it again.
        const string source = """
                              using System.Collections.Generic;
                              using Numos.API;
                              using Numos.CoreSim.State;

                              namespace MyMod;

                              [ChunkComponent("generator-tests/all-scratch")]
                              public partial struct Spark
                              {
                                  [NumosScratch] public float Flicker;
                                  [NumosScratch] public float Glow;
                              }

                              public static class Probe
                              {
                                  public static bool[] Run()
                                  {
                                      using var simulation = new AtmosSimulation(2, 1, 1);
                                      simulation.CreateAndRegisterChunk(default);
                                      var seen = new List<bool>();
                                      bool create = true;
                                      simulation.World.Solvers.Register(
                                          "generator-tests/all-scratch/probe",
                                          context =>
                                          {
                                              AtmosSolverChunk chunk = context.Chunks(simulation)[0];
                                              if (create)
                                                  chunk.GetSpark();

                                              seen.Add(chunk.HasSpark);
                                          });

                                      simulation.Tick();
                                      create = false;
                                      simulation.Tick();
                                      simulation.World.RestoreCheckpoint(simulation.World.CaptureCheckpoint());
                                      simulation.Tick();
                                      return seen.ToArray();
                                  }
                              }
                              """;

        GeneratorRunResult[] results = GeneratorHarness.RunComponents(out Compilation output, out var diagnostics, sources: [source]);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(RoslynTestSupport.Errors(output), Is.Empty);
        string generated = GeneratorHarness.GeneratedSource(results[0], "MyMod.Spark.ChunkComponent.g.cs");
        Assert.Multiple(() =>
        {
            Assert.That(generated, Does.Contain("public bool HasSpark => chunk.Has(global::MyMod.Spark.Fields.Flicker);"));
            Assert.That(generated, Does.Not.Contain("Has(global::MyMod.Spark.Fields.Glow)"));
        });

        using var stream = new MemoryStream();
        var emit = output.Emit(stream);
        Assert.That(emit.Success, Is.True, string.Join("\n", emit.Diagnostics));

        var context = new AssemblyLoadContext("ChunkComponentAllScratch", isCollectible: true);
        try
        {
            stream.Position = 0;
            Assembly assembly = context.LoadFromStream(stream);
            var seen = (bool[])assembly.GetType("MyMod.Probe", throwOnError: true)!.GetMethod("Run")!.Invoke(null, null)!;

            // Created on the first tick, still there on the second, gone after the restore.
            Assert.That(seen, Is.EqualTo(new[] { true, true, false }));
        }
        finally
        {
            context.Unload();
        }
    }

