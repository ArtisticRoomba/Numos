    [Test]
    public void UnrelatedEdit_LeavesComponentStepsCached()
    {
        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions();
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(parseOptions, FireSource);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(parseOptions, trackSteps: true);
        driver = driver.RunGenerators(compilation);

        CSharpCompilation edited = compilation.AddSyntaxTrees(
            CSharpSyntaxTree.ParseText(
                "namespace Other; internal static class Unrelated { }",
                parseOptions,
                path: "Unrelated.cs"));

        driver = driver.RunGenerators(edited);

        GeneratorRunResult result = driver.GetRunResult().Results.Single();
        var outputs = result.TrackedSteps[ChunkDataGenerator.ComponentDeclarationsStepName]
            .SelectMany(static run => run.Outputs)
            .Select(static output => output.Reason)
            .ToArray();

        Assert.That(outputs, Is.Not.Empty);
        Assert.That(
            outputs,
            Is.All.Matches<IncrementalStepRunReason>(static reason =>
                reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged));

        Assert.That(
            GeneratorHarness.SourceOutputReasons(result),
            Is.All.EqualTo(IncrementalStepRunReason.Cached));
    }

    [Test]
    public void GeneratedComponent_RegistersFieldsAtLoad()
    {
        const string source = """
                              using Numos.API;
                              using Numos.CoreSim.State;

                              namespace Smoke;

                              [ChunkComponent("generator-tests/component-smoke")]
                              public partial struct Smoke
                              {
                                  [NumosSerialize] public float Density;
                                  [NumosScratch, PerChunk(Length = 2)] public int Scratch;
                              }

                              public static class Other
                              {
                                  public static void Touch()
                                  {
                                  }
                              }
                              """;

        GeneratorHarness.RunComponents(out Compilation output, out var diagnostics, sources: [source]);
        Assert.That(diagnostics, Is.Empty);

        using var stream = new MemoryStream();
        var emit = output.Emit(stream);
        Assert.That(emit.Success, Is.True, string.Join("\n", emit.Diagnostics));

        var context = new AssemblyLoadContext("ChunkComponentSmoke", isCollectible: true);
        try
        {
            stream.Position = 0;
            Assembly assembly = context.LoadFromStream(stream);
            assembly.GetType("Smoke.Other", throwOnError: true)!.GetMethod("Touch")!.Invoke(null, null);

            // The module initializer registered the fields, so a different definition under the key conflicts.
            Assert.That(
                () => ChunkField<float>.Register("generator-tests/component-smoke/Density", rollback: true, length: 4),
                Throws.InvalidOperationException.With.Message.Contains("already registered"));

            Type fields = assembly.GetType("Smoke.Smoke+Fields", throwOnError: true)!;
            var density = (ChunkField<float>)fields.GetProperty("Density")!.GetValue(null)!;
            var scratch = (ChunkField<int>)fields.GetProperty("Scratch")!.GetValue(null)!;
            Assert.Multiple(() =>
            {
                Assert.That(density.Key, Is.EqualTo("generator-tests/component-smoke/Density"));
                Assert.That(density.Rollback, Is.True);
                Assert.That(density.Length, Is.Null);
                Assert.That(scratch.Key, Is.EqualTo("generator-tests/component-smoke/Scratch"));
                Assert.That(scratch.Rollback, Is.False);
                Assert.That(scratch.Length, Is.EqualTo(2));
                Assert.That(
                    ChunkField<float>.Register("generator-tests/component-smoke/Density", rollback: true),
                    Is.SameAs(density));
            });
        }
        finally
        {
            context.Unload();
        }
    }
