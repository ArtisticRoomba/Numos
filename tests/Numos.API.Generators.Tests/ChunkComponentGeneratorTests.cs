    private const string FireSource = """
                                      using Numos.API;
                                      using Numos.CoreSim.State;

                                      namespace MyMod;

                                      [ChunkComponent("my-mod/fire", ClearOnVacuum = true)]
                                      public partial struct Fire
                                      {
                                          [NumosSerialize] public float Exposure;
                                          [NumosSerialize, PerChunk] public int BurnCount;
                                          [NumosScratch] public float Heat;
                                      }
                                      """;

    private const string FireUsageSource = """
                                           using System;
                                           using Numos.API;

                                           namespace MyMod;

                                           internal static class Usage
                                           {
                                               public static float Read(AtmosSolverChunk chunk, AtmosSolverGasMixturePage page, AtmosSolverChunks chunks)
                                               {
                                                   Fire.View fire = chunk.GetFire();
                                                   Span<float> exposure = fire.Exposure;
                                                   Span<int> burnCount = fire.BurnCount;
                                                   Span<float> heat = fire.Heat;
                                                   float total = exposure[0] + burnCount[0] + heat[0];

                                                   if (chunk.TryGetFire(out Fire.View again) && chunk.HasFire)
                                                       total += again.Exposure[0];

                                                   if (page.TryGetFire(out Fire.View cells) && page.HasFire)
                                                       total += cells.Heat[0] + page.GetFire().BurnCount[0];

                                                   foreach (var (each, view) in chunks.WithFire())
                                                       total += view.Exposure[0] + each.VoxelCount;

                                                   foreach (var item in chunks.WithFire())
                                                       total += item.Fire.Heat[0] + item.Chunk.VoxelCount;

                                                   ChunkField<float> field = Fire.Fields.Exposure;
                                                   return total + field.Key.Length;
                                               }
                                           }
                                           """;

    [Test]
    public void Fire_GeneratesFieldsViewAndAccessorsThatCompile()
    {
        GeneratorRunResult[] results = GeneratorHarness.RunComponents(
            out Compilation output,
            out var diagnostics,
            sources: [FireSource, FireUsageSource]);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(RoslynTestSupport.Errors(output), Is.Empty);
        Assert.That(output.GetDiagnostics().Where(static d => d.Severity == DiagnosticSeverity.Warning), Is.Empty);

        // The state generator must leave the struct alone, although its fields carry [NumosSerialize].
        Assert.That(results[1].GeneratedSources, Is.Empty);

        string source = GeneratorHarness.GeneratedSource(results[0], "MyMod.Fire.ChunkComponent.g.cs");
        TestContext.Out.WriteLine(source);
        Assert.Multiple(() =>
        {
            Assert.That(source, Does.StartWith("// <auto-generated/>\n#nullable enable\n"));
            Assert.That(source, Does.Contain("partial struct Fire"));
            Assert.That(source, Does.Contain("public static class Fields"));
            Assert.That(
                source,
                Does.Contain(
                    "global::Numos.API.ChunkField<float>.Register(\"my-mod/fire/Exposure\", rollback: true, length: null, clearOnVacuum: true);"));

            Assert.That(
                source,
                Does.Contain(
                    "global::Numos.API.ChunkField<int>.Register(\"my-mod/fire/BurnCount\", rollback: true, length: 1, clearOnVacuum: true);"));

            Assert.That(
                source,
                Does.Contain(
                    "global::Numos.API.ChunkField<float>.Register(\"my-mod/fire/Heat\", rollback: false, length: null, clearOnVacuum: true);"));

            Assert.That(source, Does.Contain("public readonly ref struct View"));
            Assert.That(source, Does.Contain("public global::System.Span<float> Exposure { get; }"));
            Assert.That(source, Does.Contain("public static partial class FireComponentAccessors"));
            Assert.That(source, Does.Contain("extension(global::Numos.API.AtmosSolverChunk chunk)"));
            Assert.That(source, Does.Contain("extension(global::Numos.API.AtmosSolverGasMixturePage page)"));
            Assert.That(source, Does.Contain("extension(global::Numos.API.AtmosSolverChunks chunks)"));
            Assert.That(source, Does.Contain("public global::MyMod.Fire.View GetFire() => new(chunk);"));
            Assert.That(source, Does.Contain("public bool TryGetFire(out global::MyMod.Fire.View view)"));
            Assert.That(source, Does.Contain("public bool HasFire => chunk.Has(global::MyMod.Fire.Fields.Exposure);"));
            Assert.That(source, Does.Contain("public FireChunks WithFire() => new(chunks);"));
        });

        string initializer = GeneratorHarness.GeneratedSource(results[0], "NumosChunkDataModuleInitializer.g.cs");
        Assert.That(initializer, Does.Contain("Register(typeof(global::MyMod.Fire.Fields), \"MyMod.Fire\");"));
    }

