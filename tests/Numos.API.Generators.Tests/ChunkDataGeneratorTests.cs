    [Test]
    public void UnrelatedEdit_LeavesModelStepsCached()
    {
        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions();
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(parseOptions, FireSource);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(parseOptions, trackSteps: true);
        driver = driver.RunGenerators(compilation);

        CSharpCompilation edited = compilation.AddSyntaxTrees(
            CSharpSyntaxTree.ParseText(
                "namespace Other; internal static class Unrelated { }",
                parseOptions,
                path: "Unrelated.cs"));

        driver = driver.RunGenerators(edited);

        GeneratorRunResult result = driver.GetRunResult().Results.Single();
        string[] steps =
        [
            ChunkDataGenerator.PropertiesStepName,
            ChunkDataGenerator.LanguageVersionStepName,
            ChunkDataGenerator.ViewInfoStepName,
        ];

        foreach (string step in steps)
        {
            var outputs = result.TrackedSteps[step]
                .SelectMany(static run => run.Outputs)
                .Select(static output => output.Reason)
                .ToArray();

            Assert.That(outputs, Is.Not.Empty, step);
            Assert.That(
                outputs,
                Is.All.Matches<IncrementalStepRunReason>(static reason =>
                    reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged),
                step);
        }

        Assert.That(
            result.TrackedOutputSteps.SelectMany(static step => step.Value)
                .SelectMany(static run => run.Outputs)
                .Select(static output => output.Reason),
            Is.All.EqualTo(IncrementalStepRunReason.Cached));
    }

    [Test]
    public void ShiftedDeclarations_LeaveGeneratedFileCached()
    {
        // C# 13 so the compilation also gets a located diagnostic, which has to follow the declaration while the
        // file itself stays cached.
        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions(LanguageVersion.CSharp13);
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(parseOptions, FireSource);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(parseOptions, trackSteps: true);
        driver = driver.RunGenerators(compilation);

        SyntaxTree tree = compilation.SyntaxTrees.Single();
        CSharpCompilation edited = compilation.ReplaceSyntaxTree(
            tree,
            CSharpSyntaxTree.ParseText("// moved\n\n" + FireSource, parseOptions, path: tree.FilePath));

        driver = driver.RunGenerators(edited);

        GeneratorRunResult result = driver.GetRunResult().Results.Single();
        Assert.That(
            result.TrackedSteps[ChunkDataGenerator.PropertiesStepName]
                .SelectMany(static run => run.Outputs)
                .Select(static output => output.Reason),
            Has.Some.EqualTo(IncrementalStepRunReason.Modified));

        Assert.That(
            result.TrackedSteps[ChunkDataGenerator.TypesStepName]
                .SelectMany(static run => run.Outputs)
                .Select(static output => output.Reason),
            Is.Not.Empty.And.All.Matches<IncrementalStepRunReason>(static reason =>
                reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged));

        Diagnostic languageVersion = result.Diagnostics.Single(static diagnostic => diagnostic.Id == "NUMOSCHUNK013");
        Assert.That(languageVersion.Location.GetLineSpan().StartLinePosition.Line, Is.EqualTo(9));
    }

