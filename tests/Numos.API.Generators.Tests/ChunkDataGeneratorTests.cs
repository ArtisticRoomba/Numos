    [Test]
    public void UnrelatedEdit_LeavesModelStepsCached()
    {
        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions();
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(parseOptions, FireSource);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(parseOptions, trackSteps: true);
        driver = driver.RunGenerators(compilation);

        CSharpCompilation edited = compilation.AddSyntaxTrees(
            CSharpSyntaxTree.ParseText("namespace Other; internal static class Unrelated { }", parseOptions,
                path: "Unrelated.cs"));
        driver = driver.RunGenerators(edited);

        GeneratorRunResult result = driver.GetRunResult().Results.Single();
        string[] steps =
        [
            ChunkDataGenerator.PropertiesStepName,
            ChunkDataGenerator.LanguageVersionStepName,
            ChunkDataGenerator.ViewInfoStepName,
        ];

        foreach (string step in steps)
        {
            var outputs = result.TrackedSteps[step]
                .SelectMany(static run => run.Outputs)
                .Select(static output => output.Reason)
                .ToArray();

            Assert.That(outputs, Is.Not.Empty, step);
            Assert.That(outputs,
                Is.All.Matches<IncrementalStepRunReason>(static reason =>
                    reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged),
                step);
        }

        Assert.That(result.TrackedOutputSteps.SelectMany(static step => step.Value)
                .SelectMany(static run => run.Outputs)
                .Select(static output => output.Reason),
            Is.All.EqualTo(IncrementalStepRunReason.Cached));
    }

    [Test]
    public void ShiftedDeclarations_LeaveGeneratedFileCached()
    {
        // C# 13 so the compilation also gets a located diagnostic, which has to follow the declaration while the
        // file itself stays cached.
        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions(LanguageVersion.CSharp13);
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(parseOptions, FireSource);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(parseOptions, trackSteps: true);
        driver = driver.RunGenerators(compilation);

        SyntaxTree tree = compilation.SyntaxTrees.Single();
        CSharpCompilation edited = compilation.ReplaceSyntaxTree(tree,
            CSharpSyntaxTree.ParseText("// moved\n\n" + FireSource, parseOptions, path: tree.FilePath));
        driver = driver.RunGenerators(edited);

        GeneratorRunResult result = driver.GetRunResult().Results.Single();
        Assert.That(result.TrackedSteps[ChunkDataGenerator.PropertiesStepName]
                .SelectMany(static run => run.Outputs)
                .Select(static output => output.Reason),
            Has.Some.EqualTo(IncrementalStepRunReason.Modified));
        Assert.That(result.TrackedSteps[ChunkDataGenerator.TypesStepName]
                .SelectMany(static run => run.Outputs)
                .Select(static output => output.Reason),
            Is.Not.Empty.And.All.Matches<IncrementalStepRunReason>(static reason =>
                reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged));

        Diagnostic languageVersion = result.Diagnostics.Single(static diagnostic => diagnostic.Id == "NUMOSCHUNK013");
        Assert.That(languageVersion.Location.GetLineSpan().StartLinePosition.Line, Is.EqualTo(9));
    }

    [Test]
    public void GeneratedProperty_RegistersFieldAtRunTime()
    {
        const string source = """
                              namespace Smoke;

                              public static partial class SmokeData
                              {
                                  [Numos.API.ChunkData("generator-tests/smoke/density", Rollback = true, Length = 3)]
                                  public static partial Numos.API.ChunkField<float> Density { get; }

                                  [Numos.API.ChunkData]
                                  public static partial Numos.API.ChunkField<long> Scratch { get; }
                              }
                              """;

        GeneratorHarness.Run(out Compilation output, out var diagnostics, sources: [source]);
        Assert.That(diagnostics, Is.Empty);

        using var stream = new MemoryStream();
        var emit = output.Emit(stream);
        Assert.That(emit.Success, Is.True, string.Join("\n", emit.Diagnostics));

        // A collectible context keeps the throwaway assembly out of the default context. Numos.API itself still
        // resolves from the default context, so the registered field is the same one the rest of the process sees.
        var context = new AssemblyLoadContext("ChunkDataSmoke", isCollectible: true);
        try
        {
            stream.Position = 0;
            Assembly assembly = context.LoadFromStream(stream);
            Type type = assembly.GetType("Smoke.SmokeData", throwOnError: true)!;

            object? density = type.GetProperty("Density")!.GetValue(null);
            Assert.That(density, Is.InstanceOf<ChunkField<float>>());
            var densityField = (ChunkField<float>)density!;
            Assert.That(densityField.Key, Is.EqualTo("generator-tests/smoke/density"));
            Assert.That(densityField.Rollback, Is.True);
            Assert.That(densityField.Length, Is.EqualTo(3));
            Assert.That(ChunkField<float>.Register("generator-tests/smoke/density", rollback: true, length: 3),
                Is.SameAs(densityField));

            var scratch = (ChunkField<long>)type.GetProperty("Scratch")!.GetValue(null)!;
            Assert.That(scratch.Key, Is.EqualTo("Smoke.SmokeData.Scratch"));
            Assert.That(scratch.Rollback, Is.False);
            Assert.That(scratch.Length, Is.Null);
        }
        finally
        {
            context.Unload();
        }
    }
