    private const string HierarchySource = """
                                           using Numos.API;

                                           namespace MyMod.Fire;

                                           public interface IClock
                                           {
                                           }

                                           public interface IFireEvents
                                           {
                                           }

                                           public abstract partial class FireSolverBase : IAtmosWorldSolver
                                           {
                                               [SolverDependency]
                                               protected partial IClock Clock { get; }

                                               public abstract void Solve(AtmosWorldSolverContext context);
                                           }

                                           public sealed partial class FireSolver : FireSolverBase
