    [Test]
    public void GenericAndNestedTypes_Compile()
    {
        const string source = """
                              using Numos.API;

                              namespace MyMod;

                              public interface IRegistry<T>
                              {
                              }

                              public partial class Outer<TOuter> where TOuter : class, new()
                              {
                                  public partial struct Middle
                                  {
                                      public sealed partial class Inner<TInner> : IAtmosWorldSolver
                                          where TInner : class
                                      {
                                          [SolverDependency]
                                          private partial IRegistry<TOuter> Registry { get; }

                                          [SolverDependency(Optional = true)]
                                          private partial TInner? Extra { get; }

                                          public void Solve(AtmosWorldSolverContext context)
                                          {
                                              _ = Registry;
                                              _ = Extra;
                                          }
                                      }
                                  }
                              }
                              """;

        GeneratorRunResult result = GeneratorHarness.RunDependencies(out Compilation output, out var diagnostics,
            source);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(GeneratorHarness.Errors(output), Is.Empty);
        Assert.That(output.GetDiagnostics().Where(static d => d.Severity == DiagnosticSeverity.Warning), Is.Empty);

        string generated = GeneratorHarness.GeneratedSource(result,
            "MyMod.Outer_1+Middle+Inner_1.SolverDependencies.g.cs");
        Assert.Multiple(() =>
        {
            Assert.That(generated, Does.Contain("partial class Outer<TOuter>\n"));
            Assert.That(generated, Does.Contain("partial struct Middle\n"));
            Assert.That(generated, Does.Contain(
                "partial class Inner<TInner> : global::Numos.API.IAtmosSolverDependencies"));
            Assert.That(generated, Does.Contain(
                "resolver.Resolve<global::MyMod.IRegistry<TOuter>>(\"Registry\")"));
            Assert.That(generated, Does.Contain("resolver.ResolveOptional<TInner>()"));
        });
    }

