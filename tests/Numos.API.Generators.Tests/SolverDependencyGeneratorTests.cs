        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions()
            .WithDocumentationMode(DocumentationMode.Diagnose);
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(true, parseOptions, source);
        GeneratorHarness.CreateDriver(parseOptions, generator: new SolverDependencyGenerator())
            .RunGeneratorsAndUpdateCompilation(compilation, out Compilation output, out var diagnostics);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(output.GetDiagnostics().Where(static d => d.Severity >= DiagnosticSeverity.Warning), Is.Empty);
    }

    [Test]
    public void UnrelatedEdit_LeavesModelStepsCached()
    {
        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions();
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(true, parseOptions, FireSource);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(parseOptions, trackSteps: true,
            generator: new SolverDependencyGenerator());
        driver = driver.RunGenerators(compilation);

        CSharpCompilation edited = compilation.AddSyntaxTrees(
            CSharpSyntaxTree.ParseText("namespace Other; internal static class Unrelated { }", parseOptions,
                path: "Unrelated.cs"));
        driver = driver.RunGenerators(edited);

        GeneratorRunResult result = driver.GetRunResult().Results.Single();
        var outputs = result.TrackedSteps[SolverDependencyGenerator.PropertiesStepName]
            .SelectMany(static run => run.Outputs)
            .Select(static output => output.Reason)
            .ToArray();

        Assert.That(outputs, Is.Not.Empty);
        Assert.That(outputs,
            Is.All.Matches<IncrementalStepRunReason>(static reason =>
                reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged));
        Assert.That(result.TrackedOutputSteps.SelectMany(static step => step.Value)
                .SelectMany(static run => run.Outputs)
                .Select(static output => output.Reason),
            Is.All.EqualTo(IncrementalStepRunReason.Cached));
    }

    private static MetadataReference CompileLibrary(string source, bool runGenerator)
    {
        CSharpParseOptions parseOptions = GeneratorHarness.ParseOptions();
        Compilation compilation = GeneratorHarness.CreateCompilation(true, parseOptions, source);
        if (runGenerator)
        {
            GeneratorHarness.CreateDriver(parseOptions, generator: new SolverDependencyGenerator())
                .RunGeneratorsAndUpdateCompilation(compilation, out compilation, out var diagnostics);
            Assert.That(diagnostics, Is.Empty);
        }

        using var stream = new MemoryStream();
        var emit = compilation.Emit(stream);
        Assert.That(emit.Success, Is.True, string.Join("\n", emit.Diagnostics));
        return MetadataReference.CreateFromImage(stream.ToArray());
    }
