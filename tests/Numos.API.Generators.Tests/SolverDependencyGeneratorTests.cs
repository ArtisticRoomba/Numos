    [Test]
    public void DocumentedProject_GetsNoMissingDocWarningsFromGeneratedCode()
    {
        const string source = """
                              namespace MyMod;

                              /// <summary>
                              ///     Documented solver.
                              /// </summary>
                              public partial class DocumentedSolver : Numos.API.IAtmosWorldSolver
                              {
                                  /// <summary>
                                  ///     Documented dependency.
                                  /// </summary>
