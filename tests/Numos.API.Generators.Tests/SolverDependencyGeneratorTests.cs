    [Test]
    public void SealedSolver_GeneratesFieldsGettersAndPrivateHook()
    {
        GeneratorRunResult result = GeneratorHarness.RunDependencies(out Compilation output, out var diagnostics,
            FireSource);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(GeneratorHarness.Errors(output), Is.Empty);
        Assert.That(output.GetDiagnostics().Where(static d => d.Severity == DiagnosticSeverity.Warning), Is.Empty);

        string source = GeneratorHarness.GeneratedSource(result, "MyMod.Fire.FireSolver.SolverDependencies.g.cs");
        Assert.Multiple(() =>
        {
            Assert.That(source, Does.StartWith("// <auto-generated/>\n#nullable enable\n"));
            Assert.That(source, Does.Contain(
                "partial class FireSolver : global::Numos.API.IAtmosSolverDependencies"));
            Assert.That(source, Does.Contain(
                "private global::MyMod.Fire.IFireEvents __numosDependency_Events = null!;"));
            Assert.That(source, Does.Contain(
                "private global::MyMod.Fire.ExposureSolver? __numosDependency_Exposure;"));
            Assert.That(source, Does.Contain(
                "private partial global::MyMod.Fire.IFireEvents Events => __numosDependency_Events;"));
            Assert.That(source, Does.Contain(
                "internal partial global::MyMod.Fire.ExposureSolver? Exposure => __numosDependency_Exposure;"));
            Assert.That(source, Does.Contain(
                "void global::Numos.API.IAtmosSolverDependencies.InjectDependencies(global::Numos.API.AtmosSolverDependencyResolver resolver)"));
            Assert.That(source, Does.Contain(
                "private void InjectSolverDependencies(global::Numos.API.AtmosSolverDependencyResolver resolver)"));
            Assert.That(source, Does.Contain(
                "__numosDependency_Events = resolver.Resolve<global::MyMod.Fire.IFireEvents>(\"Events\");"));
            Assert.That(source, Does.Contain(
                "__numosDependency_Exposure = resolver.ResolveOptional<global::MyMod.Fire.ExposureSolver>();"));
            Assert.That(source, Does.Not.Contain("base."));
        });
    }

    [Test]
    public void SourceBase_RootIsVirtualAndDerivedOverridesWithBaseCall()
