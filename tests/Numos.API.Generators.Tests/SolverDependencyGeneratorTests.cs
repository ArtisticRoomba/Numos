    [Test]
    public void MetadataBase_FromGeneratedAssembly_DerivedOverrides()
    {
        const string baseSource = """
                                  using Numos.API;

                                  namespace Library;

                                  public interface IClock
                                  {
                                  }

                                  public abstract partial class LibrarySolverBase : IAtmosWorldSolver
                                  {
                                      [SolverDependency]
                                      protected partial IClock Clock { get; }

                                      public abstract void Solve(AtmosWorldSolverContext context);
                                  }
                                  """;

        const string derivedSource = """
                                     using Numos.API;

                                     namespace Consumer;

                                     public interface IFireEvents
                                     {
                                     }

                                     public sealed partial class FireSolver : Library.LibrarySolverBase
                                     {
                                         [SolverDependency]
                                         private partial IFireEvents Events { get; }

                                         public override void Solve(AtmosWorldSolverContext context)
                                         {
                                             _ = Clock;
                                             _ = Events;
                                         }
                                     }
                                     """;

        MetadataReference library = CompileLibrary(baseSource, runGenerator: true);
        GeneratorRunResult result = GeneratorHarness.RunDependencies(out Compilation output, out var diagnostics,
            [library], derivedSource);

        Assert.That(diagnostics, Is.Empty);
        Assert.That(GeneratorHarness.Errors(output), Is.Empty);
        string derived = GeneratorHarness.GeneratedSource(result, "Consumer.FireSolver.SolverDependencies.g.cs");
        Assert.That(derived, Does.Contain(
            "protected override void InjectSolverDependencies(global::Numos.API.AtmosSolverDependencyResolver resolver)"));
        Assert.That(derived, Does.Contain("base.InjectSolverDependencies(resolver);"));
    }

    [Test]
    public void MetadataBase_HandWrittenProtectedInternalHook_OverridesAsProtected()
